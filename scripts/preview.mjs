import { chromium } from '@playwright/test';
import { mkdir } from 'node:fs/promises';

await mkdir('artifacts', { recursive: true });
const browser = await chromium.launch({ channel: 'msedge', headless: true });
const page = await browser.newPage({ viewport: { width: 1440, height: 1100 }, deviceScaleFactor: 1 });
page.on('pageerror', error => console.error('PAGE ERROR:', error.message));
await page.goto('http://localhost:8081', { waitUntil: 'networkidle' });
await page.getByText('Play checkers', { exact: true }).waitFor({ timeout: 120000 });
await page.screenshot({ path: 'artifacts/desktop.png', fullPage: true });
console.log('Desktop:', await page.title(), 'Squares:', await page.getByRole('button', { name: /square \d+/ }).count());
await page.setViewportSize({ width: 390, height: 844 });
await page.waitForTimeout(400);
await page.screenshot({ path: 'artifacts/mobile.png', fullPage: true });
await page.setViewportSize({ width: 360, height: 640 });
await page.waitForTimeout(400);
await page.screenshot({ path: 'artifacts/mobile-small.png', fullPage: true });
await page.setViewportSize({ width: 844, height: 390 });
await page.waitForTimeout(400);
await page.screenshot({ path: 'artifacts/mobile-landscape.png', fullPage: true });
await page.setViewportSize({ width: 390, height: 844 });
await page.getByRole('tab', { name: 'Analysis', exact: true }).click();
await page.waitForTimeout(1400);
await page.screenshot({ path: 'artifacts/mobile-analysis.png', fullPage: true });
await page.getByRole('button', { name: 'Engine', exact: true }).click();
await page.waitForTimeout(400);
await page.screenshot({ path: 'artifacts/mobile-engine.png', fullPage: true });
await page.getByRole('button', { name: 'Close engine analysis', exact: true }).click();
await page.getByRole('tab', { name: 'Settings', exact: true }).click();
await page.getByText('Board appearance', { exact: true }).waitFor();
await page.screenshot({ path: 'artifacts/mobile-settings.png', fullPage: true });
await page.getByRole('tab', { name: 'Play', exact: true }).click();
await page.getByRole('button', { name: 'New game settings', exact: true }).click();
await page.waitForTimeout(400);
await page.screenshot({ path: 'artifacts/mobile-setup.png', fullPage: true });
console.log('Screenshots saved in artifacts/');
await browser.close();
