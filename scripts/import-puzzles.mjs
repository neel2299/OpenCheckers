import { readFile, writeFile } from 'node:fs/promises';
import { applyMove, coordinate, fromFen, legalMoves, positionKey } from '../src/game/engine.ts';
import { VARIANTS } from '../src/game/variants.ts';

// Download a pinned MIT-licensed database; compile verified alternatives offline.
const source = JSON.parse(await readFile('assets/puzzles/source.json', 'utf8'));
if (process.argv.includes('--download')) {
  for (const [path, local] of [['data/puzzles.json', 'shadow-checkers.json'], ['LICENSE', 'SHADOW-CHECKERS-LICENSE.txt']]) {
    const response = await fetch(`https://raw.githubusercontent.com/ShadowfetchStudio/shadow-checkers/${source.commit}/${path}`);
    if (!response.ok) throw Error(`Download failed: ${response.status}`);
    await writeFile(`assets/puzzles/${local}`, await response.text());
  }
}
const database = JSON.parse(await readFile('assets/puzzles/shadow-checkers.json', 'utf8'));
const pack = [];
for (const item of database) {
  const initial = fromFen(item.fen, item.variant);
  const side = initial.turn;
  const size = VARIANTS[item.variant].size;
  const route = move => move.path.map(index => coordinate(index, size)).join('-');
  const balance = position => position.board.reduce((sum, piece) => sum + (!piece ? 0 : (piece.side === side ? 1 : -1) * (piece.king ? (item.variant === 'english' ? 1.5 : 2.5) : 1)), 0);
  const start = balance(initial);
  const goal = position => {
    const moves = legalMoves(position);
    return position.turn !== side && (!moves.length || (item.goal === 'gain' && !moves[0].captures.length && balance(position) - start >= item.gain));
  };
  let calls = 0;
  const cache = new Map();
  const canSolve = (position, remaining) => {
    if (++calls > 4_000_000) throw Error(`${item.id}: solver budget exceeded`);
    if (goal(position)) return true;
    if (remaining <= 0) return false;
    const key = positionKey(position) + ':' + remaining;
    if (cache.has(key)) return cache.get(key);
    const moves = legalMoves(position);
    const result = moves.length > 0 && (position.turn === side
      ? moves.some(move => canSolve(applyMove(position, move), remaining - 1))
      : moves.every(move => canSolve(applyMove(position, move), remaining - 1)));
    cache.set(key, result);
    return result;
  };
  let position = initial;
  for (const uci of item.solution) {
    const move = legalMoves(position).find(move => route(move).replaceAll('-', '') === uci);
    if (!move) throw Error(`${item.id}: illegal source move ${uci}`);
    position = applyMove(position, move);
  }
  if (!goal(position)) throw Error(`${item.id}: source solution does not meet its goal`);
  if (!canSolve(initial, item.plies)) throw Error(`${item.id}: cannot force the goal against all defences`);
  const compile = (position, remaining, ply = 0) => {
    const branches = {};
    for (const move of legalMoves(position)) {
      const after = applyMove(position, move);
      if (!canSolve(after, remaining - 1)) continue;
      const branch = {};
      if (!goal(after)) {
        // Choose the defence that requires the longest continuation; prefer the
        // published line for ties. This is bundled data, never runtime search.
        const replies = legalMoves(after).map(reply => {
          const next = applyMove(after, reply);
          let need = 1;
          while (need < remaining - 2 && !canSolve(next, need)) need += 2;
          return { reply, next, need, preferred: route(reply).replaceAll('-', '') === item.solution[ply + 1] };
        }).sort((a, b) => b.need - a.need || Number(b.preferred) - Number(a.preferred));
        if (!replies.length) throw Error(`${item.id}: missing defence`);
        const best = replies[0];
        branch.reply = route(best.reply);
        branch.next = compile(best.next, remaining - 2, ply + 2);
        if (!Object.keys(branch.next).length) throw Error(`${item.id}: empty continuation`);
      }
      branches[route(move)] = branch;
    }
    return branches;
  };
  const solution = compile(initial, item.plies);
  pack.push({ ...item, solution });
  console.log(`${item.id}: verified ${item.plies} plies, ${Object.keys(solution).length} first move(s), ${calls} solver calls`);
}
const header = `// Generated by scripts/import-puzzles.mjs. Source and MIT license: assets/puzzles/.
import type { SolutionNode } from './puzzles.ts';
import type { VariantId } from './variants.ts';
export const PUZZLE_LICENSE = ${JSON.stringify(await readFile('assets/puzzles/SHADOW-CHECKERS-LICENSE.txt', 'utf8'))};
const puzzles: { id: string; title: string; variant: VariantId; fen: string; side: string; goal: 'gain' | 'win'; gain: number; solution: SolutionNode; plies: number; theme: string; difficulty: number }[] = `;
await writeFile('src/game/puzzlePack.ts', header + JSON.stringify(pack, null, 2) + ';\nexport default puzzles;\n');
console.log(`Imported and verified ${pack.length} puzzles from ${source.repository} @ ${source.commit}`);
